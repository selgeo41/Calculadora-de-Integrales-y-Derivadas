    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
try {
    ExprEvaluator evaluator = new ExprEvaluator();

    String funcion = Funcion.getText().trim();
    String variable = Variable.getText().trim();
    String limiteInferior = Inferior.getText().trim();
    String limiteSuperior = Superior.getText().trim();

    if (funcion.isEmpty() || variable.isEmpty() || limiteInferior.isEmpty() || limiteSuperior.isEmpty()) {
        Resultado.setText("Por favor completa todos los campos.");
        return;
    }

    // Symja usa este formato: N(Integrate(función, {variable, a, b}))
    String expresion = "Integrate(" + funcion + ", {" + variable + ", " + limiteInferior + ", " + limiteSuperior + "})";

    IExpr resultado = evaluator.eval(expresion);
    
    Resultado.setText(resultado.toString());

} catch (Exception e) {
    Resultado.setText("Error al calcular: " + e.getMessage());
}

    }//GEN-LAST:event_jButton2ActionPerformed

