    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
    try {
        ExprEvaluator evaluator = new ExprEvaluator();

        // Obtener datos de los JTextField
        String funcion = Funcion2.getText().trim()
                .replace("^", "**")
                .replace("√", "sqrt")
                .replace("**", "^")
                .replace("×", "*")
                .replace("·", "*")
                .replace(",", ".");
        String variable = Variable2.getText().trim();

        // Validar campos vacíos
        if (funcion.isEmpty() || variable.isEmpty()) {
            Resultado2.setText("Por favor ingresa la función y la variable.");
            return;
        }

        // Construir expresión para integral indefinida
        String expresion = "Integrate(" + funcion + "," + variable + ")";
        IExpr resultado = evaluator.eval(expresion);

        // Mostrar resultado
        Resultado2.setText("∫" + funcion + " d" + variable + " = " + resultado.toString() + " + C");

    } catch (Exception e) {
        Resultado2.setText("Error al calcular: " + e.getMessage());
}
    }//GEN-LAST:event_jButton3ActionPerformed

